const DICTS = { en, ja };

function detect() {
  try {
    const v = globalThis.document?.querySelector?.('meta[name="transnote-ui-lang"]')?.content;
    return v in DICTS ? v : "en";
  } catch {
    return "en";
  }
}

/** 今の画面の言語（"en" か "ja"）．読み込み時に決まる．テストでは setLang で変える． */
export let lang = detect();

/** 言語を変える（テスト用．画面の言語は再読み込みで変わる）． */
export function setLang(l) {
  lang = l in DICTS ? l : "en";
}

/** 文を引く．{name} を vars で置き換える（vars にない {name} と ${name} はそのまま）．なければ英語，それもなければ key． */
export function t(key, vars) {
  const s = DICTS[lang]?.[key] ?? en[key] ?? key;
  if (!vars) return s;
  return s.replace(/(\$?)\{(\w+)\}/g, (m, dollar, name) => (!dollar && Object.hasOwn(vars, name) ? String(vars[name]) : m));
}

/** 個数 n によって文を選ぶ：n が 1 のとき key + ".one" があればそちらを使う．vars に n も入る． */
export function tn(key, n, vars) {
  const k = n === 1 && (`${key}.one` in (DICTS[lang] ?? {}) || `${key}.one` in en) ? `${key}.one` : key;
  return t(k, { n, ...vars });
}
